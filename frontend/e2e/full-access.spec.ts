      await bravo.fill('1:30.00')
      await page.getByRole('button', {name: 'Complete competition', exact: true}).click()
      const completion = page.getByRole('dialog', {name: 'Complete competition'})
      await expect(completion.getByText(/unsaved rows.*1|1 unsaved/i)).toBeVisible()
      await completion.getByRole('button', {name: 'Cancel', exact: true}).click()
      await expect(bravo).toHaveValue('1:30.00')
      await page.getByRole('button', {name: 'Complete competition', exact: true}).click()
      await completion.getByRole('button', {name: /discard.*complete/i}).click()
      await expect(workspace.getByText('Completed', {exact: true})).toBeVisible()
      await expect(page).toHaveURL(new RegExp(`/workspace/${competitionId}/results\\?`))
      await expect(page).toHaveURL(new RegExp(`category=${categoryId}`))
      await expect(page).toHaveURL(new RegExp(`discipline=${disciplineId}`))
      await expect(category).toHaveText('R1 / Open')
