import {expect, test, type Page} from '@playwright/test'

async function select(page: Page, label: string, option: string) {
  await page.getByRole('combobox', {name: label, exact: true}).click()
  await page.getByRole('option', {name: option, exact: true}).click()
}

async function navigate(page: Page, label: string, touch: boolean) {
  if (touch) await page.getByRole('button', {name: 'Open navigation'}).click()
  const navigation = page.getByRole('navigation', {name: 'Main navigation'})
  await expect(navigation.getByRole('link', {name: 'Users', exact: true})).toHaveCount(0)
  await navigation.getByRole('link', {name: label, exact: true}).click()
}

async function noOverflow(page: Page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
}

async function saveTime(page: Page, crew: string, value: string, normalized: string, touch: boolean) {
  const input = page.getByRole('textbox', {name: `Time ${crew}`, exact: true})
  await input.fill(value)
  if (touch) {
    const row = input.locator('xpath=ancestor::*[self::tr or self::article or @role="row"][1]')
    const save = row.getByRole('button', {name: 'Save', exact: true})
    const fieldBox = await input.boundingBox(), saveBox = await save.boundingBox()
    expect(fieldBox).not.toBeNull()
    expect(saveBox).not.toBeNull()
    expect(fieldBox!.height).toBeGreaterThanOrEqual(44)
    expect(saveBox!.height).toBeGreaterThanOrEqual(44)
    expect(fieldBox!.x + fieldBox!.width).toBeLessThanOrEqual(saveBox!.x)
    expect(Math.abs(fieldBox!.y - saveBox!.y)).toBeLessThan(24)
    expect(saveBox!.x + saveBox!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
    await save.tap()
  } else {
    await input.press('Control+s')
  }
  await expect(input).toHaveValue(normalized)
}

