import { expect, test, type Page } from '@playwright/test'

async function select(page: Page, label: string, option: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

test.setTimeout(90000)

test('full access configures a race and corrects results', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Username').fill('e2e-admin')
  await page.getByLabel('Password').fill('e2e-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.getByRole('button', { name: 'Create competition' }).click()
  await page.getByLabel('Title', { exact: true }).fill('Browser race')
  await page.getByLabel('Start date').fill('2026-04-01')
  await page.getByLabel('Location').fill('River')
  await page.getByLabel('Time zone (IANA)').fill('UTC')
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Add custom category' }).click()
  await page.getByLabel('Class', { exact: true }).fill('R1')
  await page.getByLabel('Scoring group').fill('Open')
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Add discipline' }).click()
  await page.getByLabel('Name', { exact: true }).fill('Sprint')
  await page.getByRole('checkbox', { name: 'R1 / Open' }).check()
  await page.getByRole('button', { name: 'Russian points preset' }).click()
  await page.getByRole('button', { name: 'Next' }).click()
  const [setup] = await Promise.all([page.waitForResponse(response => response.url().endsWith('/api/competitions/setup') && response.request().method() === 'POST'), page.getByRole('button', { name: 'Save', exact: true }).click()])
  expect(setup.ok()).toBeTruthy()
  await expect(page.getByText('Browser race').first()).toBeVisible()

  await Promise.all([page.waitForResponse(response => response.url().includes('/api/competitions?size=100') && response.ok()), page.goto('/#/crews')])
  await select(page, 'Competition', 'Browser race')
  await select(page, 'Category', 'R1 / Open')
  for (const [name, number] of [['Alpha', '1'], ['Bravo', '2']]) {
    await page.getByRole('button', { name: 'Create crew' }).click()
    await page.getByLabel('Crew name').fill(name)
    await page.getByLabel('Region or club').fill('Club')
    await page.getByLabel('Representative').fill('Coach')
    await page.getByLabel('Start number').fill(number)
    await page.getByLabel('Surname').fill(name)
    await page.getByLabel('Given name').fill('Racer')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByText(new RegExp(`${number} — ${name} —`))).toBeVisible()
  }
  await Promise.all([page.waitForResponse(response => response.url().includes('/api/competitions?size=100') && response.ok()), page.goto('/#/start-lists')])
  await select(page, 'Competition', 'Browser race')
  await select(page, 'Discipline', 'Sprint')
  await select(page, 'Category', 'R1 / Open')
  await page.getByRole('button', { name: 'Generate start list' }).click()
  await expect(page.getByText('Alpha', { exact: true })).toBeVisible()
  await expect(page.getByText('Bravo', { exact: true })).toBeVisible()
  await Promise.all([page.waitForResponse(response => response.url().includes('/api/competitions?size=100') && response.ok()), page.goto('/#/result-grid')])
  await select(page, 'Competition', 'Browser race')
  await select(page, 'Discipline', 'Sprint')
  await select(page, 'Category', 'R1 / Open')
  const alpha = page.getByLabel('Time Alpha'), bravo = page.getByLabel('Time Bravo')
  await alpha.fill('1:10.00'); await alpha.press('Control+s'); await expect(alpha).toHaveValue('01:10.00')
  await bravo.fill('1:20.00'); await bravo.press('Control+s'); await expect(bravo).toHaveValue('01:20.00')
  await bravo.fill('1:00.00'); await bravo.press('Control+s'); await expect(bravo).toHaveValue('01:00.00')
  const competitions = await (await page.request.get('/api/competitions?size=100')).json()
  const competition = competitions.content.find((item: {title: string}) => item.title === 'Browser race')
  const categories = await (await page.request.get(`/api/competitions/${competition.id}/categories`)).json()
  await expect.poll(async () => {
    const response = await page.request.get(`/api/competitions/${competition.id}/categories/${categories[0].id}/standings`)
    expect(response.ok()).toBeTruthy()
    return (await response.json()).map((row: {crewName: string, place: number, totalPoints: number}) => [row.crewName, row.place, row.totalPoints])
  }).toEqual([['Bravo', 1, 100], ['Alpha', 2, 95]])
})
