      await expect(workspace.getByText(/01:00\.00/).first()).toBeVisible()
      await expect(workspace.getByRole('combobox', {name: 'Competition', exact: true})).toHaveCount(0)
      if (touch) await expect(workspace.getByRole('article').filter({hasText: 'Bravo'})).toBeVisible()
      else await expect(workspace.getByRole('table').getByRole('row').filter({hasText: 'Bravo'})).toBeVisible()
